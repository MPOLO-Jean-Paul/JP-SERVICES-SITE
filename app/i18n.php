function jp_auth_language_switcher_html(string $returnTo): string
{
    $buttons = '';
    foreach (jp_supported_locales() as $code => $locale) {
        $active = jp_locale() === $code;
        $buttons .= '<form action="' . e(url('/langue')) . '" method="post">'
            . '<input type="hidden" name="locale" value="' . e($code) . '">'
            . '<input type="hidden" name="return_to" value="' . e($returnTo) . '">'
            . '<button type="submit" class="' . ($active ? 'is-active' : '') . '" aria-pressed="' . ($active ? 'true' : 'false') . '">'
            . e($locale['short']) . '<span>' . e($locale['label']) . '</span></button></form>';
    }
    return '<div class="jp-auth-language" data-auth-language aria-label="Choisir la langue"><i class="fas fa-globe" aria-hidden="true"></i>' . $buttons . '</div>';
}

function jp_translate_interface_html(string $html): string
{
    if (!jp_is_english()) {
        return $html;
    }

    $protected = [];
    $html = preg_replace_callback(
        '~<([a-z][a-z0-9]*)\b[^>]*\bdata-no-translate\b[^>]*>.*?</\1>~is',
        static function (array $match) use (&$protected): string {
            $token = '___JP_NO_TRANSLATE_' . count($protected) . '___';
            $protected[$token] = $match[0];
            return $token;
        },
        $html
    ) ?? $html;

    $html = strtr($html, jp_translation_map());
    if ($protected !== []) {
        $html = strtr($html, $protected);
    }
    $html = preg_replace('~<html\b([^>]*)\blang=("|\')fr\2([^>]*)>~i', '<html$1lang="en"$3>', $html) ?? $html;

    return strtr($html, [
        'placeholder="Formation, projet, actualité ou mot-clé…"' => 'placeholder="Course, project, news or keyword…"',
        'placeholder="Rechercher par titre, compétence ou domaine…"' => 'placeholder="Search by title, skill or subject…"',
        'aria-label="Langue du site : Français"' => 'aria-label="Site language: English"',
        'aria-label="Retour en haut"' => 'aria-label="Back to top"',
        'aria-label="Fermer"' => 'aria-label="Close"',
        'aria-label="Ouvrir le menu"' => 'aria-label="Open menu"',
        'aria-label="Menu principal"' => 'aria-label="Main navigation"',
    ]);
}
