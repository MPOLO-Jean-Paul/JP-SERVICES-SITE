/**
 * Lightweight internationalisation for the application interface. Editorial
 * content created in the administration area stays in its original language.
 */
function jp_supported_locales(): array
{
    return [
        'fr' => ['label' => 'Français', 'short' => 'FR'],
        'en' => ['label' => 'English', 'short' => 'EN'],
    ];
}

function jp_locale(): string
{
    static $resolved = null;
    if (is_string($resolved)) {
        return $resolved;
    }

    $supported = jp_supported_locales();
    $candidate = strtolower((string)($_SESSION['jp_locale'] ?? $_COOKIE['jp_locale'] ?? ''));
    if (!isset($supported[$candidate])) {
        $accept = strtolower((string)($_SERVER['HTTP_ACCEPT_LANGUAGE'] ?? ''));
        $candidate = str_starts_with($accept, 'en') ? 'en' : 'fr';
    }

    $resolved = isset($supported[$candidate]) ? $candidate : 'fr';
    $_SESSION['jp_locale'] = $resolved;
    return $resolved;
}

function jp_is_english(): bool
{
    return jp_locale() === 'en';
}

function jp_tr(string $french, string $english): string
{
    return jp_is_english() ? $english : $french;
}

function jp_locale_return_path(?string $candidate): string
{
    $candidate = trim((string)$candidate);
    if ($candidate === '') {
        return url('/');
    }

    $parts = parse_url($candidate);
    if ($parts === false || isset($parts['scheme']) || isset($parts['host']) || str_starts_with($candidate, '//')) {
        return url('/');
    }

    $path = (string)($parts['path'] ?? '/');
    $base = jp_base_path();
    if ($path === '' || $path[0] !== '/' || ($base !== '' && $path !== $base && !str_starts_with($path, $base . '/'))) {
        return url('/');
    }

    $result = $path;
    if (!empty($parts['query'])) {
        $result .= '?' . $parts['query'];
    }
    if (!empty($parts['fragment'])) {
        $result .= '#' . $parts['fragment'];
    }
    return $result;
}

